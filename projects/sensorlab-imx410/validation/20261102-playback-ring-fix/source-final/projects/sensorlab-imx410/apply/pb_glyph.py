#!/usr/bin/env python3
"""The playback HUD's size tiles (font_S_imageSize_<N>) for numbers the firmware has no tile for.

    python3 -B pb_glyph.py            # writes pb_glyph.h (deterministic; test_apply checks it is current)

The playback HUD's Lua draws the clip's size as two images, string.format("font_S_imageSize_%s", PB_PixelSize*)
(MAIN 0xC2DD9BE2).  The firmware has 71 such tiles (88 x 38 at most, white anti-aliased, L == A); any other number
is a missing resource, drawn as coloured noise (OG2K_PLAN §AR).  ap.c builds one NBR pack per missing number from
the template here (one literal-only LZ4 XCI, 88 x 38) and registers it through the native NBR loader (0xC05E84D9,
as fpsup-ui and res-lab do), so the stock lookup finds it.

Emitted (C, read-only, no pointers):
  AP_TILE_STOCK[]        the 71 numbers the firmware has (sorted)
  AP_GLYPH_PACK[]        the NBR template: name "font_S_imageSize_0000", file "slpb0000.xci"
  AP_GLYPH_*             offsets in it: the name, the file name, the file-table key, the XCI pixels
  AP_GLYPH_ATLAS[]       the digits 0-9: alpha, AP_GLYPH_H rows each, AP_GLYPH_W[d] columns, row-major per digit
"""
import pathlib
import os
import re
import struct
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = pathlib.Path(os.environ.get('SL_ROOT', HERE.parents[2]))
sys.path.insert(0, str(ROOT / 'research/ui/tools'))
IMAGE = ROOT / 'out' / 'MAIN_c0000000.bin'
OUT = HERE / 'pb_glyph.h'
FONT = '/System/Library/Fonts/Supplemental/Arial Bold.ttf'
TW, TH = 88, 38                 # the tile (stock tiles are 74..87 x 38)
SIZE, GAP, BASE = 42, 1, 32     # font size (px), extra advance, the baseline row (fitted to the stock tiles: IoU 0.6-0.7)


def stock_numbers():
    d = IMAGE.read_bytes()
    return sorted({int(m.group(1)) for m in re.finditer(rb'font_S_imageSize_(\d+)\.xci', d)})


def literal_xci(w, h):
    """build_v3_reslab.literal_xci: a valid LZ4 literal-only block, pixels filled later (offset returned)."""
    raw = bytes(w * h * 2)
    ext, n = bytearray(), len(raw) - 15
    while n >= 255:
        ext.append(255)
        n -= 255
    ext.append(n)
    block = b'\xf0' + ext + raw
    head = bytearray(0x33)
    head[:4] = b'XC\0\0'
    struct.pack_into('<IHHIH', head, 4, len(block) + 23, w, h, 0x400, 0x202)
    head[0x20:0x26] = b'\x04\x22\x4d\x18\x88\x10'
    struct.pack_into('<I', head, 0x26, len(block) + 19)
    struct.pack_into('<I', head, 0x2f, len(block))
    return bytes(head) + block + bytes(4), 0x34 + len(ext)


def glyphs():
    """digit -> (width, alpha rows): Arial Bold, the stock tiles' height (ink rows 0..BASE)."""
    from PIL import Image, ImageDraw, ImageFont
    import numpy as np
    f = ImageFont.truetype(FONT, SIZE)
    out = {}
    for d in '0123456789':
        im = Image.new('L', (64, 64), 0)
        ImageDraw.Draw(im).text((8, BASE + 8), d, font=f, fill=255, anchor='ls')
        a = np.array(im)
        xs = np.where(a.max(axis=0) > 0)[0]
        a = a[8:8 + TH, xs.min():xs.max() + 1]
        out[int(d)] = (a.shape[1], a)
    return out


def compose(value, g=None):
    """the tile the camera draws for value (the same arithmetic as ap.c ap_glyph_draw): alpha TH x TW"""
    import numpy as np
    g = g or glyphs()
    s = str(value)
    gap = GAP
    while sum(g[int(c)][0] for c in s) + gap * (len(s) - 1) > TW:     # the widest numbers kern tighter
        gap -= 1
    width = sum(g[int(c)][0] for c in s) + gap * (len(s) - 1)
    x = (TW - width) // 2
    t = np.zeros((TH, TW), np.uint8)
    for c in s:
        w, a = g[int(c)]
        t[:, x:x + w] = np.maximum(t[:, x:x + w], a)
        x += w + gap
    return t


def template():
    import nbr
    data, po = literal_xci(TW, TH)
    name, fname = 'font_S_imageSize_0000', 'slpb0000.xci'
    pack = bytearray(nbr.build([nbr.Resource(name, fname, data)]))
    inv = nbr.inspect(bytes(pack))
    f = inv['files'][0]
    name_at = pack.index(name.encode() + b'\0')
    fname_at = pack.index(fname.encode() + b'\0')
    ft = struct.unpack_from('>I', pack, 0)  # noqa: F841 (layout checked below)
    key_at = next(o for o in range(len(pack) - 4) if struct.unpack_from('>I', pack, o)[0] == nbr.fnv1a(fname))
    return bytes(pack), name_at, fname_at, key_at, f['offset'] + po


def header():
    g = glyphs()
    pack, name_at, fname_at, key_at, pix = template()
    if max(w for w, _ in g.values()) * 4 - 3 * 2 > TW:
        raise SystemExit('digits too wide for the tile')
    lines = ['/* generated by pb_glyph.py -- do not edit */', '#ifndef SL_PB_GLYPH_H', '#define SL_PB_GLYPH_H']
    st = stock_numbers()
    lines.append(f'#define AP_TILE_NSTOCK {len(st)}u')
    lines.append('static const uint16_t AP_TILE_STOCK[%d] = {%s};' % (len(st), ', '.join(map(str, st))))
    lines.append(f'#define AP_GLYPH_PACK_LEN {len(pack)}u')
    lines.append(f'#define AP_GLYPH_NAME {name_at}u      /* "font_S_imageSize_0000" */')
    lines.append(f'#define AP_GLYPH_FNAME {fname_at}u     /* "slpb0000.xci" */')
    lines.append(f'#define AP_GLYPH_KEY {key_at}u       /* big-endian FNV-1a of the file name (the file table key) */')
    lines.append(f'#define AP_GLYPH_PIX {pix}u       /* the XCI pixels: TW x TH x {{L, A}} */')
    lines.append(f'#define AP_GLYPH_TW {TW}u')
    lines.append(f'#define AP_GLYPH_TH {TH}u')
    lines.append(f'#define AP_GLYPH_GAP {GAP}u')
    # the template without its zero pixel payload (filled at run time): the bytes before and after it
    head, tail = pack[:pix], pack[pix + TW * TH * 2:]
    lines.append(f'#define AP_GLYPH_HEAD {len(head)}u')
    lines.append(f'#define AP_GLYPH_TAIL {len(tail)}u')
    lines.append('static const uint8_t AP_GLYPH_TPL[%d] = {%s};' % (len(head) + len(tail),
                 ', '.join(str(b) for b in head + tail)))
    ws = [g[d][0] for d in range(10)]
    lines.append('static const uint8_t AP_GLYPH_W[10] = {%s};' % ', '.join(map(str, ws)))
    offs, atlas = [], bytearray()
    for d in range(10):
        offs.append(len(atlas))
        atlas.extend(g[d][1].astype('uint8').tobytes())
    lines.append('static const uint16_t AP_GLYPH_OFF[10] = {%s};' % ', '.join(map(str, offs)))
    lines.append('static const uint8_t AP_GLYPH_ATLAS[%d] = {%s};' % (len(atlas), ', '.join(map(str, atlas))))
    lines.append('#endif')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    OUT.write_text(header())
    print(f'{OUT.name}: {OUT.stat().st_size} B')
