#!/usr/bin/env python3
"""Playback HUD: a fourth, blank resolution-label frame, installed by fpsup-ui.

python3 -B pb_page.py       # deterministic pb_page.h, included by slqs.c

The three native Resolution objects use PB_Resolution frames 0/1/2 for UHD,
FHD and DCI4K.  Preserve their image/size/rect properties byte-for-byte and add
opacity=1 at 0/33/66, opacity=0 at 100 (enum 3).  Custom clips select 3 only
after fpui_stock_apply succeeds.  No firmware page is patched in place.
"""
import functools
import json
import pathlib
import struct
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = pathlib.Path(__file__).resolve().parents[3]
sys.path[:0] = [str(HERE.parent / 'menu'), str(ROOT / 'fpSup/uishare'), str(ROOT / 'research/ui/tools')]
import b25_plan as B
import native_ui_audit as A
from ui import fpui

PAGE = 'Playback'
OWNERS = (1843, 923, 1013)
FRAME = 3
NBU = 0xC18C0460


@functools.lru_cache(None)
def source():
    im = B.Image()
    sets = sorted(json.loads((ROOT / 'research/ui/nbu_sets.json').read_text())['sets'],
                  key=lambda x: int(x['address'], 16))
    i = next(i for i, s in enumerate(sets) if s['name'] == PAGE)
    lo, hi = (int(sets[j]['address'], 16) for j in (i, i + 1))
    B.SETS[PAGE] = (lo, hi)
    base, page, objs, records = B.walk(im, PAGE)
    return im, base, page, objs, records


def header_totals(header):
    """Last words of the property and key budget vectors; the native parser sums each vector."""
    p = 20 + B.u32(header, 16) * 8
    p += 4 + B.u32(header, p) * 12             # group budgets
    np = B.u32(header, p)
    prop_last = p + np * 4
    p += 4 + np * 4
    nk = B.u32(header, p)
    return prop_last, p + nk * 4


def build():
    im, base, page, objs, records = source()
    clips = [(o, r) for o, r in records if B.u32(r, 0) == 0x1000A and B.u32(r, 20) in OWNERS]
    assert len(clips) == len(OWNERS)
    opacity = im.pool.index(b'\0opacity\0') + 1
    prop = struct.pack('>5I', 4, 1, 0, opacity, 0)
    prop += b''.join(struct.pack('>BBIf', 1, 0, t, v) for t, v in ((0, 1), (33, 1), (66, 1), (100, 0)))
    block = fpui.Block()
    name = block.string(PAGE, fpui.NAME)
    block.op(fpui.OP_PAGE, name, base - NBU, len(page), max(objs) + 1, 0, len(prop) * 3, 3)
    edits = []
    for o, r in clips:
        c = A.parse_clip(A.Record(o, r), im.text)
        assert [(p['name'], p['kind'], p['component_ref']) for p in c['properties']] == [
            ('image', 2, 7), ('size', 1, 0), ('rect', 1, 7)]
        assert [k['time'] for k in c['properties'][0]['keys']] == [0, 33, 66]
        group = [(go, gr) for go, gr in records if B.u32(gr, 0) == 0x1000B and B.u32(gr, 24) == c['owner_id']
                 and im.text(B.u32(gr, 20)) == 'Resolution']
        assert len(group) == 1
        go, gr = group[0]
        assert B.u32(gr, 8) == 1 and im.text(B.u32(gr, 28)) == 'State' and B.u32(gr, 36) == 66
        edits += [(o + 4, len(prop)), (o + 12, 1), (go + 36, 34)]
    po, ko = header_totals(records[0][1])
    edits += [(po, 3), (ko, 12)]
    # All guards precede edits: any unexpected source leaves the runtime page untouched.
    for pos, _delta in edits:
        block.op(fpui.OP_GUARD, pos, B.u32(page, pos))
    for o, r in clips:
        block.op(fpui.OP_GUARD, o + 20, B.u32(r, 20))
    for pos, delta in edits:
        block.op(fpui.OP_ADD32, pos, delta)
    for o, r in clips:
        block.op(fpui.OP_INSERT, o + len(r), block.fragment(prop), len(prop))
    block.op(fpui.OP_DONE)
    return block.encode()


def applied(blob=None):
    im, _base, page, objs, _recs = source()
    pages = {PAGE: fpui.PageCopy(page, len(page), max(objs) + 1)}
    fpui.apply(build() if blob is None else blob, pages, fpui.Strings(im.pool))
    return bytes(pages[PAGE].data)


def header():
    data = build()
    lines = ['/* generated by pb_page.py -- do not edit */', '#ifndef SL_PB_PAGE_H', '#define SL_PB_PAGE_H',
             '#include <stdint.h>', '#define AP_PB_PAGE_FRAME 3u',
             'static const uint8_t AP_PB_PAGE[%d] = {' % len(data)]
    lines += ['    ' + ', '.join(str(x) for x in data[i:i + 20]) + ',' for i in range(0, len(data), 20)]
    return '\n'.join(lines + ['};', '#endif', ''])


if __name__ == '__main__':
    (HERE / 'pb_page.h').write_text(header())
    print('pb_page.h: %d-byte FPUI block; Playback +%d bytes' % (len(build()), len(applied()) - len(source()[2])))
