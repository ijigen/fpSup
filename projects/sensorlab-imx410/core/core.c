/* SensorLab-IMX410 core (core.h): readout_cfg.plan, smc.create, isp_formula.plan / row in freestanding C.
 *
 * Built like projects/isp-lab/sup and projects/open-gate/build/res-custom-v4: Thumb, -fropi, soft float, no libc.
 * The Cortex-A9 has no divider, so no '/' or '%' appears below: every division goes through udiv64() (shift and
 * subtract) and its Python-semantics wrappers (fdiv = //, tdiv = int(a / b)).  No floats either:
 * every Python float expression is replaced by exact integer/rational arithmetic (README: why each one matches),
 * and the three round() of a float quotient run on an integer emulation of IEEE doubles (dratio / dmul / dround).
 * The data (rule table, readout table, constants) is core_data.h, generated by export_core.py.
 * The last section is isp-lab/host/quality.py: the readouts x CRCT bins that record a crop at a RES, joined. */
#include "core.h"
#include "core_data.h"

typedef int64_t i64;
typedef uint64_t u64;

/* ------------------------------------------------------------------ arithmetic */
__attribute__((noinline)) static u64 udiv64(u64 n, u64 d, u64 *rem)
{
    u64 q = 0, r = 0;
    for (int i = 63; i >= 0; i--) {
        r = r << 1 | ((n >> i) & 1u);
        if (r >= d) { r -= d; q |= (u64)1 << i; }
    }
    if (rem) *rem = r;
    return q;
}

/* truncating signed division (C semantics; Python int(a / b) for exact rationals) */
static i64 tdiv(i64 a, i64 b)
{
    int neg = (a < 0) != (b < 0);
    u64 q = udiv64(a < 0 ? (u64)-a : (u64)a, b < 0 ? (u64)-b : (u64)b, 0);
    return neg ? -(i64)q : (i64)q;
}

/* Python a // b (floor) */
static i64 fdiv(i64 a, i64 b)
{
    int neg = (a < 0) != (b < 0);
    u64 r, q = udiv64(a < 0 ? (u64)-a : (u64)a, b < 0 ? (u64)-b : (u64)b, &r);
    if (neg) return r ? -(i64)q - 1 : -(i64)q;
    return (i64)q;
}

static i64 cdiv(i64 a, i64 b) { return -fdiv(-a, b); }          /* math.ceil(a / b) */
static i64 pmod(i64 a, i64 b) { return a - fdiv(a, b) * b; }     /* Python a % b */
static i64 imin(i64 a, i64 b) { return a < b ? a : b; }
static i64 imax(i64 a, i64 b) { return a > b ? a : b; }

/* ---- Python float, emulated exactly with integers (IEEE binary64, round to nearest even; normal range only).
 * A value is m * 2^e with 2^52 <= m < 2^53 (m = 0: zero).  This is what makes vmax = round(CLK / (hm * fps))
 * bit-identical to the Python even at round() ties, where the exact rational answer and the float one differ
 * (fps 52800/1001 on HMAX 400: exact 3412.5 -> 3412, Python's floats -> 3413). */
typedef struct { u64 m; int e; } dbl;

/* round (hi:lo) * 2^e to 53 bits */
static dbl dnorm(u64 hi, u64 lo, int e, int sticky)
{
    dbl r = {0, 0};
    if (!hi && !lo) return r;
    int msb = 0;                                             /* bit index of the leading one in hi:lo */
    if (hi) { msb = 64; u64 t = hi; while (t >>= 1) msb++; }
    else { u64 t = lo; while (t >>= 1) msb++; }
    if (msb > 52) {
        int sh = msb - 52;
        u64 g, rest;                                         /* guard bit, bits below it */
        u64 m;
        if (sh < 64) {
            m = (lo >> sh) | (sh ? hi << (64 - sh) : 0);
            g = (lo >> (sh - 1)) & 1u;
            rest = sh >= 2 ? lo & (((u64)1 << (sh - 1)) - 1u) : 0;
        } else {
            m = hi >> (sh - 64);
            g = sh == 64 ? lo >> 63 : (hi >> (sh - 65)) & 1u;
            rest = sh == 64 ? lo & (((u64)1 << 63) - 1u) : (lo | (hi & (((u64)1 << (sh - 65)) - 1u)));
        }
        m &= ((u64)1 << 53) - 1u;
        if (g && (rest || sticky || (m & 1u))) m++;
        e += sh;
        if (m >> 53) { m >>= 1; e++; }
        r.m = m; r.e = e;
    } else {
        r.m = lo << (52 - msb); r.e = e - (52 - msb);        /* fits: exact (callers pass sticky only above) */
    }
    return r;
}

/* the float nearest n / d (Python int / int is correctly rounded); one copy: a loop gains nothing inlined */
__attribute__((noinline)) static dbl dratio(u64 n, u64 d)
{
    /* long division, one quotient bit at a time from 2^63 down, until 55 significant bits (53 + guard + 1) */
    u64 r = 0, q = 0;
    int pos = 63, got = 0, e = 0;
    for (;; pos--) {
        r = r << 1 | (pos >= 0 ? (n >> pos) & 1u : 0);
        int bit = r >= d;
        if (bit) r -= d;
        if (got || bit) { q = q << 1 | (u64)bit; got++; }
        if (got == 55) { e = pos; break; }
        if (pos < -200) return (dbl){0, 0};
    }
    int sticky = r != 0 || (e > 0 && (n & (((u64)1 << e) - 1u)) != 0);
    return dnorm(0, q, e, sticky);
}

static dbl dmul(dbl a, u64 k)                               /* float(k) * a, k < 2^53 */
{
    u64 a0 = a.m & 0xFFFFFFFFu, a1 = a.m >> 32, k0 = k & 0xFFFFFFFFu, k1 = k >> 32;
    u64 p00 = a0 * k0, p01 = a0 * k1, p10 = a1 * k0, p11 = a1 * k1;
    u64 mid = (p00 >> 32) + (p01 & 0xFFFFFFFFu) + (p10 & 0xFFFFFFFFu);
    u64 lo = (p00 & 0xFFFFFFFFu) | mid << 32;
    u64 hi = p11 + (p01 >> 32) + (p10 >> 32) + (mid >> 32);
    return dnorm(hi, lo, a.e, 0);
}

static dbl ddiv_int(u64 n, dbl b)                           /* float(n) / b, n < 2^53 */
{
    dbl q = dratio(n, b.m);
    q.e -= b.e;
    return q;
}

/* Python round(x) of a positive float: round half to even */
static i64 dround(dbl x)
{
    if (!x.m) return 0;
    if (x.e >= 0) return (i64)(x.m << x.e);
    int sh = -x.e;
    if (sh > 63) return 0;                                   /* m < 2^63: below 1/2 */
    u64 q = x.m >> sh, rem = x.m & (((u64)1 << sh) - 1u), half = (u64)1 << (sh - 1);
    if (rem > half || (rem == half && (q & 1u))) q++;
    return (i64)q;
}

static i64 pyround_div(u64 n, u64 d) { return dround(dratio(n, d)); }   /* round(n / d), Python floats */

/* Python round(x, 3) * 1000: correctly rounded from the exact binary value, half to even (x * 1000 is exact) */
static i64 dround_milli(dbl x) { dbl y = {x.m * 1000u, x.e}; return dround(y); }

static int dlt(dbl a, dbl b)                                /* a < b, positive floats (Python float <) */
{
    if (!a.m || !b.m) return !a.m && b.m;
    return a.e != b.e ? a.e < b.e : a.m < b.m;
}

int32_t core_fps_milli(uint32_t clocks) { return (int32_t)dround_milli(dratio(CD_CLK, clocks)); }

/* JS x.toFixed(places) * 10^places of a positive double: half up from its exact value */
static i64 js_fixed_d(dbl x, int places)
{
    u64 m = x.m;
    for (int p = 0; p < places; p++) m *= 10u;               /* < 2^63: exact */
    if (!x.m) return 0;
    if (x.e >= 0) return (int64_t)(m << x.e);
    int sh = -x.e;
    if (sh > 63) return 0;
    u64 q = m >> sh, rem = m & (((u64)1 << sh) - 1u), half = (u64)1 << (sh - 1);
    return (int64_t)(q + (rem >= half));                      /* toFixed: the larger n on a tie */
}

int64_t core_js_fixed(uint64_t num, uint64_t den, int places)
{
    if (!num || !den || places < 0 || places > 3) return 0;
    return js_fixed_d(dratio(num, den), places);
}

int64_t core_py_vmax(uint32_t hm, uint32_t num, uint32_t den)
{
    return dround(ddiv_int(CD_CLK, dmul(dratio(num, den), hm)));
}

static void zero(void *p, uint32_t n)
{
    volatile uint8_t *b = p;
    for (uint32_t i = 0; i < n; i++) b[i] = 0;
}

static void put16(uint8_t *b, uint32_t o, i64 v) { b[o] = (uint8_t)v; b[o + 1] = (uint8_t)((u64)v >> 8); }
static void put32(uint8_t *b, uint32_t o, u64 v)
{
    b[o] = (uint8_t)v; b[o + 1] = (uint8_t)(v >> 8); b[o + 2] = (uint8_t)(v >> 16); b[o + 3] = (uint8_t)(v >> 24);
}

/* ------------------------------------------------------------------ readout_cfg */
int core_n_keys(void) { return CD_N_KEYS; }

int core_key_index(const char *name)
{
    for (int k = 0; k < CD_N_KEYS; k++) {
        int i = 0;
        while (i < 16 && cd_key_name[k][i] && cd_key_name[k][i] == name[i]) i++;
        if (i < 16 && cd_key_name[k][i] == 0 && name[i] == 0) return k;
    }
    return -1;
}

static i64 line_width(const cd_ro_t *r, i64 w)                  /* readout_cfg.line_width */
{
    return (r->mh == 1 && w < 6000) ? w - CD_LINE_SHORT : w;
}

static i64 full_rows(const cd_ro_t *r)                          /* readout_cfg.full_rows */
{
    i64 n = r->rows_full ? r->rows_full : fdiv(tdiv(CD_SENSOR_H, r->mv), 2) * 2;   /* int(4040 / mv) // 2 * 2 */
    return (r->mv == 3 && r->is_new) ? n - CD_V3_FULL_SKIP : n;
}

static int sens_add(core_plan *p, u64 reg, u64 val)
{
    if (p->n_sensor >= CORE_MAX_SENSOR) return CORE_E_SENSOR;
    p->sensor[p->n_sensor][0] = (uint32_t)reg;
    p->sensor[p->n_sensor][1] = (uint32_t)val;
    p->n_sensor++;
    return 0;
}

#define TRY(x) do { int e_ = (x); if (e_) return e_; } while (0)

int core_readout_plan(int key, int cw, int ch, int ow, int oh, uint32_t fps_num, uint32_t fps_den,
                      int v016, int hmax, int hdr, int rows, core_plan *p)
{
    zero(p, sizeof *p);
    if (key < 0 || key >= CD_N_KEYS) return CORE_E_KEY;
    const cd_ro_t *r = &cd_ro[key];
    i64 mh = r->mh, mv = r->mv;
    /* sw = cw / mh, sh = ch / mv as rationals swn / swd, ch / mv */
    i64 swn = cw, swd = mh;
    /* fmt = min(w : line_width(w) >= sw - 1e-6)  <=>  line_width(w) * mh >= cw */
    i64 fmt = -1, fmax = 0;
    int fi = -1;
    for (int i = 0; i < r->nfmt; i++) {
        if (r->fmt_w[i] > fmax) fmax = r->fmt_w[i];
        if (line_width(r, r->fmt_w[i]) * mh >= cw && (fmt < 0 || r->fmt_w[i] < fmt)) { fmt = r->fmt_w[i]; fi = i; }
    }
    /* within 0.5 %: line_width(max) >= sw * 0.995  <=>  1000 * lw * mh >= 995 * cw */
    if (fmt < 0 && 1000 * line_width(r, fmax) * mh >= 995 * (i64)cw) {
        fmt = fmax; swn = line_width(r, fmt); swd = 1;
        for (int i = 0; i < r->nfmt; i++) if (r->fmt_w[i] == fmax) fi = i;
    }
    if (fmt < 0) return CORE_E_WIDE;
    /* windowed = sh < 4040 / mv - 2  <=>  ch < 4040 - 2 mv */
    int windowed = (i64)ch < CD_SENSOR_H - 2 * mv;
    if (mh == 3 && mv == 1) return CORE_E_H3V1;
    if ((i64)ow * swd > swn || (windowed && (i64)oh * mv > ch)) return CORE_E_UPSCALE;
    if (windowed && r->centre < 0) return CORE_E_NOWIN;
    i64 H = cdiv(ch, 2 * mv);                                    /* math.ceil(sh / 2) */
    i64 hm = hmax ? hmax : r->hmin;
    if (hm < r->hmin) return CORE_E_HMAX;
    i64 rows_out = windowed ? 2 * H : full_rows(r), y_crop = 0;
    if (rows >= 0) {                                             /* R16: a centred row crop of the full-height frame */
        if (windowed) return CORE_E_ROWCROP;
        if (rows <= 0 || (rows & 1) || rows > rows_out) return CORE_E_ROWCROP;
        y_crop = fdiv(rows_out - rows, 4) * 2;
        rows_out = rows;
    }
    if (oh > rows_out) return CORE_E_ROWS;
    i64 lines = (windowed ? rows_out : pyround_div(CD_SENSOR_H, (u64)mv)) + r->over;   /* int(round(4040 / mv)) */
    i64 y_skip = (mv == 3 && r->is_new) ? (windowed ? CD_V3_MARGIN : CD_V3_FULL_SKIP) : 0;
    lines += windowed ? y_skip : 0;
    y_skip += y_crop;                                            /* R16: the TIM starts below the dropped rows */
    i64 b = v016 < 0 ? r->v016 : v016;
    if (b < r->v016 && (r->v016_min < 0 || b < r->v016_min)) return CORE_E_V016;
    i64 vmin = lines + 2 * b + 12, vmax;
    if (fps_num) {
        /* round(CLK / (hm * fps)), fps = the float nearest num / den, every step a Python float operation */
        vmax = dround(ddiv_int(CD_CLK, dmul(dratio(fps_num, fps_den), (u64)hm)));
        if (vmax < vmin && r->v016_min >= 0 && v016 < 0) { b = r->v016_min; vmin = lines + 2 * b + 12; }
        if (vmax < vmin) return CORE_E_VMIN;
        if (vmax > CD_VMAX_MAX) return CORE_E_VMAX;
    } else {
        vmax = vmin;
    }
    i64 rx_w = cdiv(swn, 12 * swd) * 12;
    i64 lw = line_width(r, fmt);
    i64 raster_w = imin(lw == fmt ? fmt : fdiv(lw, 16) * 16, cdiv(swn, 16 * swd) * 16);
    for (int i = 0; i < r->extra_n; i++)
        TRY(sens_add(p, cd_pairs[r->extra_start + i].reg, cd_pairs[r->extra_start + i].val));
    TRY(sens_add(p, 0x0001, r->fmt_code[fi]));
    if (windowed) {
        i64 raw = r->centre - H * mv, st = raw;
        for (int d = 0; d <= 2; d++) {                           /* min((raw+k) = 1 mod 4) by (|k|, value) */
            if (pmod(raw - d, 4) == 1) { st = raw - d; break; }
            if (pmod(raw + d, 4) == 1) { st = raw + d; break; }
        }
        if (st < CD_WIN_TOP || st + 2 * H * mv > CD_WIN_BOTTOM) return CORE_E_WINROWS;
        i64 Hr = H + fdiv(y_skip, 2);
        st -= y_skip * mv;
        if (st < CD_WIN_TOP) return CORE_E_MARGIN;
        if (mv == 3 && r->is_new && CD_V3_SKIP_ON) {
            Hr = H + fdiv(CD_V3_SKIP, 2); st -= CD_V3_SKIP * mv;
            if (st < CD_WIN_TOP) return CORE_E_SKIP;
            for (int i = 0; i < CD_N_V3WIN; i++) TRY(sens_add(p, cd_v3win[i].reg, cd_v3win[i].val));
        }
        TRY(sens_add(p, 0x0003, 1));
        TRY(sens_add(p, 0x0022, st & 0xFF)); TRY(sens_add(p, 0x0023, st >> 8));
        TRY(sens_add(p, 0x0024, Hr & 0xFF)); TRY(sens_add(p, 0x0025, Hr >> 8));
    } else {
        int has3 = 0;
        for (int i = 0; i < p->n_sensor; i++) if (p->sensor[i][0] == 0x0003) has3 = 1;
        if (!has3) TRY(sens_add(p, 0x0003, 0));
    }
    if (b != r->v016) TRY(sens_add(p, 0x0016, (u64)b));
    if (hdr) {
        uint32_t v242 = 0;
        int n = 0;
        for (int i = 0; i < p->n_sensor; i++) {                  /* dict(sensor): the last write wins */
            if (p->sensor[i][0] == 0x0242) v242 = p->sensor[i][1];
        }
        for (int i = 0; i < p->n_sensor; i++) {
            if (p->sensor[i][0] == 0x0242 || p->sensor[i][0] == 0x0738) continue;
            p->sensor[n][0] = p->sensor[i][0]; p->sensor[n][1] = p->sensor[i][1]; n++;
        }
        p->n_sensor = n;
        TRY(sens_add(p, 0x0242, v242 | 1u));
        TRY(sens_add(p, 0x0738, (u64)(i64)hdr));
    }
    if (!ow || !oh) return CORE_E_ZERO;                         /* rwzm = [sw / ow, sh / oh] */
    p->key = key; p->hdr = hdr; p->donor = r->donor; p->bits = r->bits; p->mh = (int32_t)mh; p->mv = (int32_t)mv;
    p->is_new = r->is_new; p->cw = cw; p->ch = ch; p->ow = ow; p->oh = oh;
    p->fmt_w = (int32_t)fmt; p->line_w = (int32_t)lw; p->raster_w = (int32_t)raster_w; p->out_h = (int32_t)rows_out;
    p->y_skip = (int32_t)y_skip; p->receiver_lines = (int32_t)lines;
    p->sw_num = (int32_t)swn; p->sw_den = (int32_t)swd; p->sh_num = ch; p->sh_den = (int32_t)mv;
    p->fast_set = r->fast_set ? 1 : 0;
    p->tim_line = (r->fast_set && fmt < 6000) ? (int32_t)(fmt + 4) : 0;
    p->r38_words = (r->fast_set && fmt < 6000) ? (int32_t)(fdiv(fmt, 12) + 1) : 0;
    p->hmax = (int32_t)hm; p->vmax = (int32_t)vmax; p->vmin = (int32_t)vmin;
    p->rx_width = (int32_t)rx_w; p->rx_end = (int32_t)(lines - 2);
    return 0;
}

/* ------------------------------------------------------------------ smc: mode_rules 'exact' formulas */
typedef struct {
    const int32_t *a;
    int hd, fullw, dtab, dtab_own, full1x1;      /* mode_rules.derive (v33 = inzoom = rep = 0: a new mode) */
} der_t;

static int lut(const int16_t *t, int lo, int hi, i64 k, i64 *v)
{
    if (k < lo || k > hi || t[k - lo] < 0) return CORE_E_LOOKUP;
    *v = t[k - lo];
    return 0;
}

static int derive(const int32_t *a, der_t *d)
{
    i64 hb = a[A_HBIN], vb = a[A_VBIN], W = a[A_WIDTH], H = a[A_HEIGHT];
    i64 num = W * hb, den = H * vb;
    if (den == 0) return CORE_E_ZERO;
    if (den < 0) { num = -num; den = -den; }
    d->a = a;
    d->hd = 17 * den < 10 * num && 10 * num < 20 * den;        /* 1.7 < W hb / (H vb) < 2.0 */
    d->fullw = W * hb >= 6048;
    d->dtab = -1; d->dtab_own = 0;
    for (int i = 0; i < CD_N_DEFECT; i++)
        if (cd_defect[i].hb == hb && cd_defect[i].vb == vb && cd_defect[i].w == W && cd_defect[i].h == H) {
            d->dtab = cd_defect[i].id; d->dtab_own = 1;
        }
    if (d->dtab < 0) {
        d->dtab = 97;
        for (int i = 0; i < CD_N_DEFECT_FB; i++)
            if (cd_defect_fb[i].hb == hb && cd_defect_fb[i].vb == vb) d->dtab = cd_defect_fb[i].id;
    }
    d->full1x1 = hb == 1 && vb == 1 && W == 6064 && H == 4042;
    return 0;
}

static void r28(i64 W, i64 H, i64 o[8])
{
    /* mode_rules._r28: _even_round(W * K / 16) = 2 * int(W * K / 32 + 0.5) etc., K = num / den exactly */
    i64 cw = 2 * tdiv(W * CD_K_EVAL_W_NUM + 16 * CD_K_EVAL_W_DEN, 32 * CD_K_EVAL_W_DEN);
    i64 ch = 2 * fdiv(H * CD_K_EVAL_H_NUM, 32 * CD_K_EVAL_H_DEN);
    i64 aw = 2 * tdiv(W * CD_K_AF_W_NUM + 32 * CD_K_AF_W_DEN, 64 * CD_K_AF_W_DEN);
    i64 ah = 2 * tdiv(H * CD_K_AF_H_NUM + 32 * CD_K_AF_H_DEN, 64 * CD_K_AF_H_DEN);
    o[0] = cw; o[1] = ch; o[2] = fdiv(W - 16 * cw, 2); o[3] = 2 * fdiv(H - 16 * ch, 4);
    o[4] = aw; o[5] = ah; o[6] = 2 * fdiv(fdiv(W, 2) - 16 * aw, 4); o[7] = 2 * fdiv(fdiv(H, 2) - 16 * ah, 4);
}

int core_r28(int32_t width, int32_t height, int32_t out[8])
{
    i64 o[8];
    r28(width, height, o);
    for (int i = 0; i < 8; i++) out[i] = (int32_t)o[i];
    return 0;
}

static int r38_ob(const der_t *d, int group, i64 o[3])
{
    static const int16_t S[7] = {-1, 24, 10, 8, -1, -1, 6}, N[7] = {-1, 3, 3, 2, -1, -1, 1};
    i64 vb = d->a[A_VBIN], s, n;
    TRY(lut(S, 0, 6, vb, &s));
    TRY(lut(N, 0, 6, vb, &n));
    if (group == 1 && vb == 1 && d->a[A_ACQ]) s = 30;
    o[0] = s; o[1] = s + ((i64)1 << n); o[2] = n;
    return 0;
}

static int r68_flag(const der_t *d)
{
    return (d->a[A_ACQ] && !d->full1x1) || !d->dtab_own;
}

static void r68_crop(const der_t *d, i64 o[4])
{
    const int32_t *a = d->a;
    o[0] = o[1] = o[2] = o[3] = 0;
    if (!r68_flag(d)) return;
    i64 hb = a[A_HBIN], vb = a[A_VBIN];
    o[0] = hb * a[A_X0] - 8;
    if (vb == 1) o[1] = a[A_Y0] - 40 + (a[A_WIN] ? a[A_WSTART] - 59 : 0);
    else o[1] = vb * a[A_Y0] - 32;
    o[2] = hb * a[A_WIDTH];
    o[3] = (d->fullw && vb > 1) ? 4042 : vb * a[A_HEIGHT];
}

static int exact(int tab, int off, const int32_t *a, i64 *v)
{
    der_t d;
    TRY(derive(a, &d));
    i64 t[8];
    switch (tab << 16 | off) {
    /* TIM / REG window: identity */
    case T_TIM << 16 | 0x04: *v = a[A_HMAX]; return 0;
    case T_TIM << 16 | 0x06: *v = a[A_TAIL]; return 0;
    case T_TIM << 16 | 0x08: *v = a[A_VMAX]; return 0;
    case T_TIM << 16 | 0x0A: *v = a[A_X0]; return 0;
    case T_TIM << 16 | 0x0C: *v = a[A_X1]; return 0;
    case T_TIM << 16 | 0x0E: *v = a[A_Y0]; return 0;
    case T_TIM << 16 | 0x10: *v = a[A_Y1]; return 0;
    /* REG: off is the row byte offset; the register is cd_reg_order[off / 4 - 1] */
    /* META */
    case T_META << 16 | 0x04: case T_META << 16 | 0x14: case T_META << 16 | 0x24: *v = a[A_WIDTH]; return 0;
    case T_META << 16 | 0x08: case T_META << 16 | 0x18: case T_META << 16 | 0x28: *v = a[A_HEIGHT]; return 0;
    case T_META << 16 | 0x2C: *v = (a[A_ACQ] && d.fullw) ? fdiv(6000, a[A_HBIN]) : 0; return 0;
    case T_META << 16 | 0x30: *v = (a[A_ACQ] && d.fullw) ? fdiv(4000, a[A_VBIN]) : 0; return 0;
    case T_META << 16 | 0x34: *v = (a[A_ACQ] && d.fullw) ? fdiv(a[A_WIDTH] - fdiv(6000, a[A_HBIN]), 2) : 0; return 0;
    case T_META << 16 | 0x38: *v = (a[A_ACQ] && d.fullw) ? fdiv(a[A_HEIGHT] - fdiv(4000, a[A_VBIN]), 2) : 0; return 0;
    case T_META << 16 | 0x3C:
        if (a[A_BITS] == 12) *v = 0; else if (a[A_BITS] == 14) *v = 1; else return CORE_E_LOOKUP;
        return 0;
    case T_META << 16 | 0x40: *v = a[A_FPSN]; return 0;
    case T_META << 16 | 0x44: case T_META << 16 | 0x4C: *v = a[A_HBIN]; return 0;
    case T_META << 16 | 0x48: *v = a[A_VADD]; return 0;
    case T_META << 16 | 0x50: *v = a[A_VBIN]; return 0;
    case T_META << 16 | 0x54: *v = d.hd ? 1 : 2; return 0;
    case T_META << 16 | 0x58: *v = d.fullw ? 0 : 1; return 0;
    case T_META << 16 | 0x5C: *v = a[A_F5C]; return 0;
    case T_META << 16 | 0x60: *v = a[A_CLS]; return 0;
    /* R14 */
    case T_R14 << 16 | 0x0C: {
        static const int16_t M[7] = {-1, 0x22, 0x33, 0x22, -1, -1, 0x11};
        TRY(lut(M, 0, 6, a[A_VBIN], v)); *v |= 0x100; return 0;
    }
    /* R28 */
    case T_R28 << 16 | 0x04: r28(a[A_WIDTH], a[A_HEIGHT], t); *v = t[2]; return 0;
    case T_R28 << 16 | 0x06: r28(a[A_WIDTH], a[A_HEIGHT], t); *v = t[3]; return 0;
    case T_R28 << 16 | 0x08: r28(a[A_WIDTH], a[A_HEIGHT], t); *v = t[0]; return 0;
    case T_R28 << 16 | 0x0A: r28(a[A_WIDTH], a[A_HEIGHT], t); *v = t[1]; return 0;
    case T_R28 << 16 | 0x0E: r28(a[A_WIDTH], a[A_HEIGHT], t); *v = t[6]; return 0;
    case T_R28 << 16 | 0x10: r28(a[A_WIDTH], a[A_HEIGHT], t); *v = t[7]; return 0;
    case T_R28 << 16 | 0x12: r28(a[A_WIDTH], a[A_HEIGHT], t); *v = t[4]; return 0;
    case T_R28 << 16 | 0x14: r28(a[A_WIDTH], a[A_HEIGHT], t); *v = t[5]; return 0;
    /* R38 */
    case T_R38 << 16 | 0x04: *v = d.hd ? 8 : 0; return 0;
    case T_R38 << 16 | 0x06: *v = imax(0, fdiv(a[A_X0], 12) - 1); return 0;
    case T_R38 << 16 | 0x08: *v = fdiv(a[A_X0], 12) + cdiv(a[A_WIDTH], 12) + 1; return 0;
    case T_R38 << 16 | 0x0A: *v = a[A_Y0] - 2 + ((d.hd && a[A_VBIN] > 1) ? 2 : 0); return 0;
    case T_R38 << 16 | 0x0C: *v = a[A_Y1] + 2 + ((d.hd && a[A_VBIN] > 1) ? 2 : 0); return 0;
    case T_R38 << 16 | 0x10: case T_R38 << 16 | 0x1A: *v = imax(0, fdiv(a[A_X0], 12) - 1) + 4; return 0;
    case T_R38 << 16 | 0x12: case T_R38 << 16 | 0x1C: *v = fdiv(a[A_X1], 12) - 3; return 0;
    case T_R38 << 16 | 0x14: TRY(r38_ob(&d, 1, t)); *v = t[0]; return 0;
    case T_R38 << 16 | 0x16: TRY(r38_ob(&d, 1, t)); *v = t[1]; return 0;
    case T_R38 << 16 | 0x18: TRY(r38_ob(&d, 1, t)); *v = t[2] | (d.hd ? 0xC000 : 0); return 0;
    case T_R38 << 16 | 0x1E: TRY(r38_ob(&d, 2, t)); *v = t[0]; return 0;
    case T_R38 << 16 | 0x20: TRY(r38_ob(&d, 2, t)); *v = t[1]; return 0;
    case T_R38 << 16 | 0x22: TRY(r38_ob(&d, 2, t)); *v = t[2]; return 0;
    /* R68 */
    case T_R68 << 16 | 0x04: *v = d.dtab; return 0;
    case T_R68 << 16 | 0x08: *v = r68_flag(&d); return 0;
    case T_R68 << 16 | 0x0C: *v = 97; return 0;
    case T_R68 << 16 | 0x10: r68_crop(&d, t); *v = t[0]; return 0;
    case T_R68 << 16 | 0x14: r68_crop(&d, t); *v = t[1]; return 0;
    case T_R68 << 16 | 0x18: r68_crop(&d, t); *v = t[2]; return 0;
    case T_R68 << 16 | 0x1C: r68_crop(&d, t); *v = t[3]; return 0;
    case T_R68 << 16 | 0x20: {
        static const int16_t M[4] = {-1, 0, 7, 2};
        return lut(M, 0, 3, a[A_HBIN], v);
    }
    case T_R68 << 16 | 0x24: {
        static const int16_t M[7] = {-1, 0, 7, 1, -1, -1, 3};
        return lut(M, 0, 6, a[A_VBIN], v);
    }
    case T_R68 << 16 | 0x2C: *v = a[A_DYO] ? a[A_DYO] : (a[A_VBIN] == 2 && a[A_ACQ]) ? 2 : 0; return 0;
    /* R68 SensorAdjustment: only the 11 calibration modes (rep); a new mode is none of them */
    case T_R68 << 16 | 0x30: case T_R68 << 16 | 0x32: case T_R68 << 16 | 0x34: case T_R68 << 16 | 0x38:
    case T_R68 << 16 | 0x3C: case T_R68 << 16 | 0x40: case T_R68 << 16 | 0x44: case T_R68 << 16 | 0x48:
    case T_R68 << 16 | 0x4C: case T_R68 << 16 | 0x50: case T_R68 << 16 | 0x54: case T_R68 << 16 | 0x58:
    case T_R68 << 16 | 0x5A: case T_R68 << 16 | 0x5C: case T_R68 << 16 | 0x60: case T_R68 << 16 | 0x64:
        *v = 0; return 0;
    }
    if (tab == T_REG && off >= 4) {
        uint32_t reg = cd_reg_order[(off >> 2) - 1];
        switch (reg) {
        case 0x0003: *v = a[A_WIN]; return 0;
        case 0x0022: *v = a[A_WSTART] & 0xFF; return 0;
        case 0x0023: *v = a[A_WSTART] >> 8; return 0;
        case 0x0024: *v = a[A_WH] & 0xFF; return 0;
        case 0x0025: *v = a[A_WH] >> 8; return 0;
        }
    }
    return CORE_E_EXACT;
}

/* ------------------------------------------------------------------ smc: the fitted rules */
static int rule_value(const cd_rule_t *ru, const int32_t *a, i64 *v)
{
    switch (ru->kind) {
    case RK_EXACT:
        return exact(ru->tab, ru->off, a, v);
    case RK_CONST:
        *v = ru->arg; return 0;
    case RK_CAT: {
        const cd_cat_t *c = &cd_cat[ru->arg];
        for (int i = 0; i < c->n; i++) {
            const cd_cat_ent_t *e = &cd_cat_ent[c->start + i];
            if (e->k0 == a[c->k0] && (c->k1 == 0xFF || e->k1 == a[c->k1])) { *v = e->v; return 0; }
        }
        return CORE_E_CAT;
    }
    case RK_LIN: {
        const cd_lin_t *l = &cd_lin[ru->arg];
        i64 g = l->g == 0xFF ? 0 : a[l->g], x = a[l->x];
        for (int i = 0; i < l->n; i++) {
            const cd_lin_ent_t *e = &cd_lin_ent[l->start + i];
            if (e->g == g) {                                     /* int(p/q * x + r/s), Fractions: truncation */
                *v = tdiv((i64)e->p * x * e->s + (i64)e->r * e->q, (i64)e->q * e->s);
                return 0;
            }
        }
        return CORE_E_LIN;
    }
    case RK_BYTE:
        *v = ((i64)a[ru->arg & 0xFF] >> (ru->arg >> 8)) & 0xFF; return 0;
    case RK_NEAREST: {
        int best = -1, any = 0;
        i64 bd = 0;
        for (int i = 0; i < CD_N_STOCK; i++) if (cd_stock[i].cls == a[A_CLS]) any = 1;
        for (int i = 0; i < CD_N_STOCK; i++) {
            if (any && cd_stock[i].cls != a[A_CLS]) continue;
            i64 dw = cd_stock[i].w - (i64)a[A_WIDTH], dh = cd_stock[i].h - (i64)a[A_HEIGHT];
            i64 dd = (dw < 0 ? -dw : dw) + (dh < 0 ? -dh : dh);
            if (best < 0 || dd < bd) { best = i; bd = dd; }
        }
        *v = cd_near[ru->arg][best];
        return 0;
    }
    }
    return CORE_E_RULE;
}

static uint8_t *row_of(core_mode *m, int tab)
{
    switch (tab) {
    case T_TIM: return m->tim;
    case T_META: return m->meta;
    case T_R28: return m->r28;
    case T_R38: return m->r38;
    case T_R14: return m->r14;
    case T_R68: return m->r68;
    case T_REG: return m->reg;
    }
    return m->r10;
}

static int reg_write(core_mode *m, uint32_t reg, uint32_t val)
{
    for (int i = 0; i < CD_N_REG; i++)
        if (cd_reg_order[i] == reg) { put32(m->reg, 4u * (1u + (uint32_t)i), val); return 0; }
    return CORE_E_REG;                                           /* list.index ValueError */
}

int core_smc_create(const core_plan *p, core_mode *m)
{
    zero(m, sizeof *m);
    if (p->key < 0 || p->key >= CD_N_KEYS) return CORE_E_KEY;
    const cd_ro_t *r = &cd_ro[p->key];
    int32_t *a = m->attrs;
    i64 cls = r->cls, hb = r->mh, vb = r->mv, x0, y0, t;
    if (!cls) return CORE_E_LOOKUP;
    /* smc.attrs_from_plan */
    TRY(lut(cd_base_x0, CD_BASE_X0_LO, CD_BASE_X0_HI, hb, &x0));
    x0 += fdiv((i64)p->fmt_w - p->raster_w, 2);
    if (p->line_w < p->fmt_w) x0 = imax(0, fdiv(imin(x0, (i64)p->line_w - p->raster_w), 2) * 2);
    if (r->y0) y0 = r->y0;
    else TRY(lut(cd_base_y0, CD_BASE_Y0_LO, CD_BASE_Y0_HI, cls, &y0));
    y0 += p->y_skip;
    i64 win = 0, s22 = 0, s23 = 0, s24 = 0, s25 = 0, v016 = r->v016;
    for (int i = 0; i < p->n_sensor; i++) {                      /* dict(p['sensor']): the last write wins */
        uint32_t g = p->sensor[i][0], v = p->sensor[i][1];
        if (g == 0x0003) win = v; else if (g == 0x0022) s22 = v; else if (g == 0x0023) s23 = v;
        else if (g == 0x0024) s24 = v; else if (g == 0x0025) s25 = v; else if (g == 0x0016) v016 = v;
    }
    a[A_CLS] = (int32_t)cls; a[A_HBIN] = (int32_t)hb; a[A_VBIN] = (int32_t)vb;
    TRY(lut(cd_vadd, CD_VADD_LO, CD_VADD_HI, vb, &t)); a[A_VADD] = (int32_t)t;
    a[A_BITS] = r->bits; a[A_WIDTH] = p->raster_w; a[A_HEIGHT] = p->out_h;
    a[A_HMAX] = p->hmax; a[A_TAIL] = p->hmax; a[A_VMAX] = p->vmax; a[A_F5C] = (int32_t)(2 * v016);
    a[A_X0] = (int32_t)x0; a[A_X1] = (int32_t)(x0 + p->raster_w); a[A_Y0] = (int32_t)y0;
    a[A_Y1] = (int32_t)(y0 + p->out_h);
    if ((i64)p->hmax * p->vmax <= 0) return CORE_E_ZERO;
    a[A_FPSN] = (int32_t)pyround_div(CD_CLK, (u64)((i64)p->hmax * p->vmax));   /* int(round(CLK / (hmax * vmax))) */
    a[A_WIN] = (int32_t)win; a[A_WSTART] = (int32_t)(s22 | s23 << 8); a[A_WH] = (int32_t)(s24 | s25 << 8);
    a[A_ROWS] = p->out_h; a[A_ACQ] = 0; a[A_CROP] = 0; a[A_CONT] = 0; a[A_Y_SKIP] = p->y_skip;
    a[A_DYO] = r->is_new ? (vb == 2 ? 2 : vb == 3 ? 66 : 0) : 0;
    /* smc.build */
    for (int i = 0; i < CD_N_RULES; i++) {
        const cd_rule_t *ru = &cd_rules[i];
        i64 v;
        TRY(rule_value(ru, a, &v));
        if (ru->tab == T_REG) put32(m->reg, ru->off, (u64)v);
        else put16(row_of(m, ru->tab), ru->off, v);
    }
    /* R10 by class, then the plan's sensor writes (the fast Family A set first) */
    TRY(lut(cd_r10, CD_R10_LO, CD_R10_HI, cls, &t));
    put32(m->r10, 0, (u64)t);
    if (p->fast_set)
        for (int i = 0; i < CD_N_FAST; i++) TRY(reg_write(m, cd_fast[i].reg, cd_fast[i].val));
    for (int i = 0; i < p->n_sensor; i++) TRY(reg_write(m, p->sensor[i][0], p->sensor[i][1]));
    return 0;
}

/* ------------------------------------------------------------------ isp_formula v2 */
#define UNITY 1024
#define UNITY_STOCK 1023
#define RWZM_MAX 8191
#define SRC_MAX 2100
#define VIS_MAX_W 2000
#define MARGIN_W 16
#define MARGIN_H 10
#define E3_W_MAX (3 * SRC_MAX)
#define STANDBY_DIV 3
#define STANDBY_W 2000
#define STANDBY_H 1334

static i64 zst(i64 v) { return v <= UNITY ? UNITY_STOCK : v; }   /* isp_formula._z */
static i64 hbin_enum(i64 b) { return b == 3 ? 1 : 0; }            /* HBIN {1: 0, 3: 1} (checked in record) */

uint32_t core_fbits(uint32_t x)
{
    if (!x) return 0;
    int e = 31;
    while (!((x >> e) & 1u)) e--;
    uint32_t mant;
    if (e <= 23) {
        mant = x << (23 - e);
    } else {
        int sh = e - 23;
        uint32_t rem = x & ((1u << sh) - 1u), half = 1u << (sh - 1);
        mant = x >> sh;
        if (rem > half || (rem == half && (mant & 1u))) mant++;
        if (mant >> 24) { mant >>= 1; e++; }
    }
    return (uint32_t)(e + 127) << 23 | (mant & 0x7FFFFFu);
}

static uint32_t fbits_i(int32_t x)
{
    return x < 0 ? 0x80000000u | core_fbits((uint32_t)-(i64)x) : core_fbits((uint32_t)x);
}

static void setw(core_isp_result *o, int off, i64 v)
{
    o->words[off >> 2] = (uint32_t)v;
    o->mask[off >> 7] |= 1u << ((off >> 2) & 31);
}

/* visible (R6): the record's act in preview pixels, fitted inside the source; -1 = empty preview */
static int isp_visible(const core_spec *s, i64 act0, i64 act1, i64 ph, i64 pv, i64 *vw_o, i64 *vh_o, i64 *aw_o, i64 *ah_o)
{
    i64 W = s->win_w, H = s->win_h;
    i64 src0 = fdiv(W * UNITY, ph), src1 = fdiv(H * UNITY, pv);
    i64 vfh = imax(s->zh, UNITY) * s->hbin, vfv = imax(s->zv, UNITY) * s->vbin;
    i64 aw = fdiv(act0 * vfh, ph), ah = fdiv(act1 * vfv, pv);
    i64 sw = src0 - MARGIN_W, sh = src1 - MARGIN_H;
    if (aw <= 0 || ah <= 0 || sw <= 0 || sh <= 0) return -1;
    i64 vw = aw, vh = ah, cap = imin(sw, VIS_MAX_W);
    if (vw > cap) { vw = cap; vh = fdiv(cap * ah, aw); }
    if (vh > sh) { vh = sh; vw = fdiv(sh * aw, ah); }
    vw = imin(fdiv(vw + 15, 16) * 16, fdiv(sw, 16) * 16);
    if (vw == VIS_MAX_W) {
        static const int16_t KNOWN_H[2] = {1125, 1334};
        for (int i = 0; i < 2; i++) {
            i64 dk = vh - KNOWN_H[i];
            if ((dk < 0 ? -dk : dk) <= 4 && KNOWN_H[i] <= sh) vh = KNOWN_H[i];
        }
    }
    *vw_o = vw; *vh_o = vh; *aw_o = aw; *ah_o = ah;
    return 0;
}

int core_isp_plan(const core_spec *s, core_isp_result *o)
{
    zero(o, sizeof *o);
#define NOTPOSSIBLE(w) do { o->why = (w); return CORE_E_ISP; } while (0)
    i64 zh = s->zh, zv = s->zv, W = s->win_w, H = s->win_h;
    /* record (R1, R2, R8) */
    if (!(zh == UNITY || (UNITY < zh && zh <= RWZM_MAX))) NOTPOSSIBLE(ISP_WHY_RWZM);
    if (!(zv == UNITY || (UNITY < zv && zv <= RWZM_MAX))) NOTPOSSIBLE(ISP_WHY_RWZM);
    if ((s->vbin != 1 && s->vbin != 3) || (s->hbin != 1 && s->hbin != 3)) NOTPOSSIBLE(ISP_WHY_BIN);
    if ((s->vbin == 3 || s->hbin == 3) && zh == UNITY && zv == UNITY) NOTPOSSIBLE(ISP_WHY_UNITYBIN);
    i64 most0 = fdiv(fdiv(W, s->hbin) * UNITY, zh) & ~(i64)15, most1 = fdiv(fdiv(H, s->vbin) * UNITY, zv) & ~(i64)1;
    i64 rec0 = s->has_rec ? s->rec_w : most0, rec1 = s->has_rec ? s->rec_h : most1;
    if (pmod(rec0, 16) || pmod(rec1, 2) || rec0 > most0 || rec1 > most1 || rec0 <= MARGIN_W || rec1 <= MARGIN_H)
        NOTPOSSIBLE(ISP_WHY_REC);
    i64 act0 = rec0 - MARGIN_W, act1 = rec1 - MARGIN_H;
    /* path (R4, R5, R9, R10, R12: the preview source is at most CD_SRC_MAX_H rows, R14) */
    i64 fh = zh * s->hbin, fv = zv * s->vbin, ph, pv;
    int path;
    if (s->vbin == 3 || s->hbin == 3) {
        if (fdiv(W * UNITY, fh) > SRC_MAX || fdiv(H * UNITY, fv) > CD_SRC_MAX_H) NOTPOSSIBLE(ISP_WHY_CBIN_FIT);
        path = PATH_C; ph = fh; pv = fv;
    } else if (fh == UNITY && fv == UNITY) {
        if (W <= SRC_MAX && act0 <= VIS_MAX_W && H <= CD_SRC_MAX_H) { path = PATH_B; ph = pv = UNITY; }
        else {
            i64 k = imax(imax(cdiv(W, SRC_MAX), cdiv(act0, VIS_MAX_W)), cdiv(H, CD_SRC_MAX_H));
            path = PATH_D; ph = pv = k * UNITY;
        }
    } else {
        int c_fits = fdiv(W * UNITY, fh) <= SRC_MAX && fdiv(H * UNITY, fv) <= CD_SRC_MAX_H;
        if (fh == fv && c_fits) { path = PATH_C; ph = fh; pv = fv; }
        else {
            if (W <= SRC_MAX && H <= CD_SRC_MAX_H) { path = PATH_E1; ph = pv = UNITY; }
            else if (W <= E3_W_MAX) { path = PATH_E3; ph = pv = 3 * UNITY; }
            else NOTPOSSIBLE(ISP_WHY_NO_F);
            if (c_fits) {   /* R14: an E preview that cannot hold the record's act takes C, if C shows it all */
                i64 vw, vh, aw, ah;
                if (isp_visible(s, act0, act1, ph, pv, &vw, &vh, &aw, &ah)) NOTPOSSIBLE(ISP_WHY_EMPTY);
                if (vw < aw || vh < ah) {
                    if (isp_visible(s, act0, act1, fh, fv, &vw, &vh, &aw, &ah)) NOTPOSSIBLE(ISP_WHY_EMPTY);
                    if (vw >= aw && vh >= ah) { path = PATH_C; ph = fh; pv = fv; }
                }
            }
        }
    }
    /* preview_fields */
    i64 pre[4];
    if (path == PATH_C) { pre[0] = hbin_enum(s->hbin); pre[1] = hbin_enum(s->vbin); pre[2] = zst(zh); pre[3] = zst(zv); }
    else if (path == PATH_E3) { pre[0] = pre[1] = 1; pre[2] = pre[3] = UNITY_STOCK; }
    else { pre[0] = pre[1] = 0; pre[2] = zst(ph); pre[3] = zst(pv); }
    i64 src0 = fdiv(W * UNITY, ph), src1 = fdiv(H * UNITY, pv);
    i64 vw, vh, aw, ah;
    if (isp_visible(s, act0, act1, ph, pv, &vw, &vh, &aw, &ah)) NOTPOSSIBLE(ISP_WHY_EMPTY);
    i64 ras0 = vw + MARGIN_W, ras1 = vh + MARGIN_H;
    /* R7 plane codes (a dict lookup: KeyError, not NotPossible) */
    i64 pl0, pl1;
    switch (s->bits) {
    case 8: pl0 = 10; pl1 = 10; break;
    case 10: pl0 = 10; pl1 = 9; break;
    case 12: pl0 = 7; pl1 = 7; break;
    case 14: pl0 = 7; pl1 = 8; break;
    default: o->why = ISP_WHY_BITS; return CORE_E_LOOKUP;
    }
    setw(o, 0x00, rec0); setw(o, 0x04, rec1); setw(o, 0xDC, rec0); setw(o, 0xE4, rec1);
    setw(o, 0x24, act0); setw(o, 0x2C, act1); setw(o, 0xF4, W); setw(o, 0xF8, H);
    setw(o, 0x0C, ras0); setw(o, 0x10, ras1); setw(o, 0xD8, ras0); setw(o, 0xE0, ras1);
    setw(o, 0x20, vw); setw(o, 0x28, vh);
    setw(o, 0x58, pre[0]); setw(o, 0xC4, pre[1]); setw(o, 0x60, pre[2]); setw(o, 0xD0, pre[3]);
    setw(o, 0x64, zst(zh)); setw(o, 0xD4, zst(zv)); setw(o, 0x5C, hbin_enum(s->hbin)); setw(o, 0xC8, hbin_enum(s->vbin));
    setw(o, 0xFC, fbits_i(s->sx)); setw(o, 0x100, fbits_i(s->sy));
    setw(o, 0x80, pl0); setw(o, 0x84, pl1); setw(o, 0xB0, s->hirate ? 1 : 0);
    setw(o, 0x38, path == PATH_E3 ? 16 : 1); setw(o, 0x1C, 1); setw(o, 0x88, 0); setw(o, 0x90, 1); setw(o, 0xC0, 0);
    o->rec[0] = (int32_t)rec0; o->rec[1] = (int32_t)rec1; o->act[0] = (int32_t)act0; o->act[1] = (int32_t)act1;
    o->path = path;
    for (int i = 0; i < 4; i++) o->preview[i] = (int32_t)pre[i];
    o->source[0] = (int32_t)src0; o->source[1] = (int32_t)src1;
    o->visible[0] = (int32_t)vw; o->visible[1] = (int32_t)vh;
    o->raster[0] = (int32_t)ras0; o->raster[1] = (int32_t)ras1;
    o->standby[0] = (int32_t)imin(STANDBY_W, fdiv(vw * ph * s->sx, STANDBY_DIV * UNITY));
    o->standby[1] = (int32_t)imin(STANDBY_H, fdiv(vh * pv * s->sy, STANDBY_DIV * UNITY));
    return 0;
#undef NOTPOSSIBLE
}

int core_isp_row(const core_spec *s, const uint32_t base[65], uint32_t out[65])
{
    core_isp_result o;
    int e = core_isp_plan(s, &o);
    if (e) return e;
    for (int i = 0; i < 65; i++) out[i] = ((o.mask[i >> 5] >> (i & 31)) & 1u) ? o.words[i] : base[i];
    return 0;
}

/* ------------------------------------------------------------------ quality.py: the qualities for a crop + RES */
int core_line_hmax(int key, int w)
{
    if (key < 0 || key >= CD_N_KEYS) return CORE_E_KEY;
    i64 hm = cdiv((i64)w * CD_LINE_PX_DEN, CD_LINE_PX_NUM);     /* isp_formula.min_line_clk: ceil(w * 2 / 29) */
    if (cd_ro[key].bits == 14 && w > CD_WIDE14_W) hm = imax(hm, CD_WIDE14_HMAX);   /* R15 */
    return hm > cd_ro[key].hmin ? (int)hm : 0;
}

static int value_error(int e)                                    /* readout_cfg.plan ValueError */
{
    return (e <= CORE_E_WIDE && e >= CORE_E_SKIP) || e == CORE_E_ROWCROP;
}

static void copy_q(core_quality *d, const core_quality *s)
{
    volatile int32_t *o = (volatile int32_t *)d;
    const int32_t *i = (const int32_t *)s;
    for (uint32_t k = 0; k < sizeof *d / 4; k++) o[k] = i[k];
}

/* quality.readout: the plan at max fps, re-planned at the cap when it is faster; fills q's readout fields.
 * p is scratch.  A ValueError-class code means the key is not offered; anything else the Python raises through. */
static int q_readout(int key, i64 cw, i64 ch, int rows, uint32_t cn, uint32_t cd, core_plan *p, core_quality *q)
{
    const cd_ro_t *r = &cd_ro[key];
    i64 sw = fdiv(cw, r->mh), sh = fdiv(ch, r->mv);
    if (ch >= CD_SENSOR_H) sh = imin(sh, full_rows(r));         /* full height: the rows the readout delivers */
    if (rows >= 0) sh = rows;                                    /* R16 */
    TRY(core_readout_plan(key, (int)cw, (int)ch, (int)sw, (int)sh, 0, 1, -1, 0, 0, rows, p));
    /* R11 on the raster the ISP processes (the isp window), not sw; the raster does not depend on HMAX */
    int hmax = core_line_hmax(key, p->raster_w);
    if (hmax) TRY(core_readout_plan(key, (int)cw, (int)ch, (int)sw, (int)sh, 0, 1, -1, hmax, 0, rows, p));
    q->vmin = p->vmin;
    /* fps_max > cap: plan at the cap, and only then do the args carry it */
    q->capped = cn && dlt(dratio(cn, cd), dratio(CD_CLK, (u64)p->hmax * (u64)p->vmin));
    if (q->capped) TRY(core_readout_plan(key, (int)cw, (int)ch, (int)sw, (int)sh, cn, cd, -1, hmax, 0, rows, p));
    dbl fps = dratio(CD_CLK, (u64)p->hmax * (u64)p->vmax);
    q->key = key; q->mh = r->mh; q->mv = r->mv;
    q->cw = (int32_t)cw; q->ch = (int32_t)ch; q->sw = (int32_t)sw; q->sh = (int32_t)sh; q->hmax = hmax; q->rows = rows;
    q->hm = p->hmax; q->vmax = p->vmax;
    /* the planner's floor: with an fps it falls back to 0016 = v016_min, vmin = lines + 2 * 0016 + 12 */
    q->vmin_lo = r->v016_min >= 0 ? (int32_t)imin(q->vmin, (i64)p->receiver_lines + 2 * r->v016_min + 12) : q->vmin;
    q->fps_milli = (int32_t)dround_milli(fps);
    q->win_w = p->raster_w; q->win_h = p->out_h;
    q->lines = p->receiver_lines;
    return 0;
}

static i64 zr(i64 src, i64 dst)                                 /* quality._z: within 0.2 % is 1:1 */
{
    i64 z = fdiv(src * UNITY, dst);
    return z < UNITY + 2 ? UNITY : z;
}

/* quality.isp: per axis, RWZM takes what the sensor merge and the CRCT bin leave of DC / RES; R2 1025 */
static int q_isp(core_quality *q, i64 rw, i64 rh, int vbin, int hbin, const i64 *nom, core_spec *s, core_isp_result *o)
{
    i64 W = q->win_w, H = q->win_h, zh = UNITY, zv = UNITY;
    /* visible tolerance: an axis that delivers less than the DC on the readout grid keeps the DC's RWZM */
    i64 bw = nom ? imax(W, nom[0]) : W, bh = nom ? imax(H, nom[1]) : H;
    if (hbin == 3 || bw > rw) { if (!rw) return CORE_E_ZERO; zh = zr(fdiv(bw, hbin), rw); }
    if (vbin == 3 || bh > rh) { if (!rh) return CORE_E_ZERO; zv = zr(fdiv(bh, vbin), rh); }
    if ((hbin == 3 || vbin == 3) && zh == UNITY && zv == UNITY) zh = zv = CD_Q_NEAR_UNITY;
    i64 most_h = zv > UNITY ? fdiv(fdiv(H, vbin) * UNITY, zv) : fdiv(H, vbin);
    q->hbin = hbin; q->vbin = vbin; q->zh = (int32_t)zh; q->zv = (int32_t)zv;
    q->rec_w = (int32_t)rw; q->rec_h = (int32_t)(imin(rh, most_h) & ~(i64)1);
    core_quality_spec(q, s);
    TRY(core_isp_plan(s, o));
    q->path = o->path;
    return 0;
}

void core_quality_spec(const core_quality *q, core_spec *s)
{
    zero(s, sizeof *s);
    s->win_w = q->win_w; s->win_h = q->win_h; s->zh = q->zh; s->zv = q->zv; s->sx = q->mh; s->sy = q->mv;
    s->vbin = q->vbin; s->hbin = q->hbin; s->bits = q->bits; s->hirate = 0;
    s->has_rec = 1; s->rec_w = q->rec_w; s->rec_h = q->rec_h;
}

int core_quality_plan(const core_quality *q, uint32_t fps_num, uint32_t fps_den, core_plan *p)
{
    return core_readout_plan(q->key, q->cw, q->ch, q->sw, q->sh, fps_num, fps_den, -1, q->hmax, 0, q->rows, p);
}

/* quality.pick: one per quality, the fastest variant (round(fps, 3)), the first listed on a tie */
static int q_pick(core_quality *out, int n, int max, const core_quality *c)
{
    for (int i = 0; i < n; i++)
        if (out[i].mh == c->mh && out[i].mv == c->mv && out[i].ad == c->ad && out[i].hbin == c->hbin &&
            out[i].vbin == c->vbin) {
            if (c->fps_milli > out[i].fps_milli) copy_q(&out[i], c);
            return n;
        }
    if (n >= max) return CORE_E_FULL;
    copy_q(&out[n], c);
    return n + 1;
}

/* quality.short_ok: rec no larger than rw x rh, each axis at most tol = tn / td short (exact for the rationals the
 * float tol stands for: test_core proves it per tol) */
static int short_ok(i64 rec_w, i64 rec_h, i64 rw, i64 rh, u64 tn, u64 td)
{
    return rec_w <= rw && rec_h <= rh && (u64)(rw - rec_w) * td <= tn * (u64)rw && (u64)(rh - rec_h) * td <= tn * (u64)rh;
}

int core_short_ok(int rec_w, int rec_h, int rw, int rh, uint32_t tol_num, uint32_t tol_den)
{
    return short_ok(rec_w, rec_h, rw, rh, tol_num, tol_den);
}

/* quality.r16_rows: the DC's rows on the readout's output grid, even; with tol the whole frame when it is at most tol
 * short of them; -1 (None) when the full frame holds fewer */
static int r16_rows(int key, i64 ch, int tol, u64 tn, u64 td)
{
    i64 rows = fdiv(ch, cd_ro[key].mv) & ~(i64)1, full = full_rows(&cd_ro[key]);
    if (tol && rows > full && (u64)full * td >= (u64)rows * (td - tn)) return (int)full;
    return rows <= full ? (int)rows : -1;
}

int core_r16_rows(int key, int ch, uint32_t tol_num, uint32_t tol_den)
{
    if (key < 0 || key >= CD_N_KEYS || ch < 0) return CORE_E_KEY;
    return r16_rows(key, ch, tol_den != 0, tol_num, tol_den);
}

int core_qualities(int cw, int ch, int ow, int oh, uint32_t cap_num, uint32_t cap_den, core_quality *out, int max)
{
    return core_qualities_tol(cw, ch, ow, oh, cap_num, cap_den, 0, 0, out, max);
}

int core_qualities_tol(int cw, int ch, int ow, int oh, uint32_t cap_num, uint32_t cap_den, uint32_t tol_num,
                       uint32_t tol_den, core_quality *out, int max)
{
    if (cw < 0 || ch < 0 || ow < 0 || oh < 0 || (cap_num && cap_num < cap_den) || (cap_num && !cap_den) ||
        (tol_den && tol_num > tol_den))
        return CORE_E_INPUT;
    int tol = tol_den != 0;
    core_plan p;
    core_spec s;
    core_isp_result o;
    core_quality base, wide;
    int n = 0, seq = 0;
    for (int k = 0; k < CD_N_QUAL; k++) {                        /* quality.candidates */
        int key = cd_qual[k].key, e, wide_e = 1, rows = -1;      /* wide_e 1: not planned yet */
        i64 rch = ch;
        zero(&base, sizeof base);
        e = q_readout(key, cw, ch, -1, cap_num, cap_den, &p, &base);
        if (e) {
            if (!value_error(e)) return e;
            if (ch >= CD_SENSOR_H) continue;
            /* R16: the readout cannot window the DC -> full height, the TIM keeps the DC's rows (centred, even) */
            rch = CD_SENSOR_H;
            rows = r16_rows(key, ch, tol, tol_num, tol_den);
            if (rows < 0) continue;                              /* the frame holds less than the DC */
            zero(&base, sizeof base);
            e = q_readout(key, cw, rch, rows, cap_num, cap_den, &p, &base);
            if (e) { if (value_error(e)) continue; return e; }
        }
        base.bits = cd_qual[k].bits; base.ad = cd_qual[k].ad;
        i64 nom[2] = {fdiv(cw, cd_ro[key].mh), fdiv(ch, cd_ro[key].mv) & ~(i64)1};   /* the DC on the readout grid */
        const i64 *np = tol ? nom : 0;
        for (int b = 0; b < CD_N_QBINS; b++) {
            int hbin = cd_qbins[b][0], vbin = cd_qbins[b][1];
            core_quality *c = &base;
            e = q_isp(c, ow, oh, vbin, hbin, np, &s, &o);
            if (e == CORE_E_ISP) {
                /* RWZM 1025 (R2) loses up to 16 px of a 1:1 record: 16 px more sensor crop buys them back */
                if ((hbin == 1 && vbin == 1) || (i64)cw + CD_Q_WIDEN > CD_Q_SENSOR_W) continue;
                if (wide_e == 1) {
                    zero(&wide, sizeof wide);
                    wide_e = q_readout(key, (i64)cw + CD_Q_WIDEN, rch, rows, cap_num, cap_den, &p, &wide);
                    wide.bits = base.bits; wide.ad = base.ad;
                }
                if (wide_e) { if (value_error(wide_e)) continue; return wide_e; }
                c = &wide;
                e = q_isp(c, ow, oh, vbin, hbin, np, &s, &o);
                if (e == CORE_E_ISP) continue;
            }
            if (e) return e;
            if ((o.rec[0] != ow || o.rec[1] != oh) &&                /* a quality never changes the RES ... */
                (!tol || !short_ok(o.rec[0], o.rec[1], ow, oh, tol_num, tol_den))) continue;   /* ... beyond tol */
            c->rec_w = o.rec[0]; c->rec_h = o.rec[1];
            c->vis_w = o.rec[0] - CD_Q_MARGIN_W; c->vis_h = o.rec[1] - CD_Q_MARGIN_H;
            c->rs_us = (int32_t)dround_milli(dmul(dratio((u64)c->hm * (u64)c->lines, CD_CLK), 1000u));
            c->seq = seq++;
            n = q_pick(out, n, max, c);
            if (n < 0) return n;
        }
    }
    for (int i = 1; i < n; i++)                                  /* matrix order: where each winner was listed */
        for (int j = i; j > 0 && out[j - 1].seq > out[j].seq; j--) {
            core_quality t;
            copy_q(&t, &out[j]); copy_q(&out[j], &out[j - 1]); copy_q(&out[j - 1], &t);
        }
    return n;
}
